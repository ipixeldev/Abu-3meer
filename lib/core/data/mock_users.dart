    .where(
      (u) =>
          u.team == Team.barcelona &&
          u.lastActiveAt != null &&
          DateTime.now().difference(u.lastActiveAt!).inHours < 24,
    )
    .length;
int get madridActiveFans => _mockUsers
    .where(
      (u) =>
          u.team == Team.realMadrid &&
          u.lastActiveAt != null &&
          DateTime.now().difference(u.lastActiveAt!).inHours < 24,
    )
    .length;

/// Average XP per active fan.
double get barcaAvgXp => barcaActiveFans > 0
    ? _mockUsers
              .where(
                (u) =>
                    u.team == Team.barcelona &&
                    u.lastActiveAt != null &&
                    DateTime.now().difference(u.lastActiveAt!).inHours < 24,
              )
              .fold(0, (a, b) => a + b.xp) /
          barcaActiveFans
    : 0;
double get madridAvgXp => madridActiveFans > 0
    ? _mockUsers
              .where(
                (u) =>
                    u.team == Team.realMadrid &&
                    u.lastActiveAt != null &&
